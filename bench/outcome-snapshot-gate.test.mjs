import test from 'node:test';
import assert from 'node:assert/strict';
import {verifySnapshotOutcomes} from './outcome-snapshot-gate.mjs';
const recipient='0x'+'1'.repeat(40),token='0x'+'2'.repeat(40);
const block=n=>'0x'+n.toString(16).padStart(64,'0');
const entry=(asset,balanceWei)=>({recipient,asset,balanceWei});
const path={chainId:'8453',outcome:[{recipient,asset:'native',deltaWei:'100'},{recipient,asset:token,deltaWei:'7'}]};
const before={chainId:'8453',blockNumber:'10',blockHash:block(10),balances:[entry('native','1000'),entry(token,'30')]};
const after={chainId:'8453',blockNumber:'11',blockHash:block(11),balances:[entry('native','1100'),entry(token,'37')]};
const check=(p=path,a=before,b=after)=>verifySnapshotOutcomes(p,a,b);
test('matches supplied native and token deltas',()=>assert.equal(check().checkedRecipients,2));
test('rejects mismatched recipient delta',()=>assert.throws(()=>check(path,before,{...after,balances:[entry('native','1099'),entry(token,'37')]}),/delta/));
test('rejects missing asset balance',()=>assert.throws(()=>check(path,before,{...after,balances:[entry('native','1100')]}),/coverage/));
test('rejects duplicate balance keys',()=>assert.throws(()=>check(path,{...before,balances:[...before.balances,entry('native','1000')]},after),/Duplicate/));
test('rejects same block',()=>assert.throws(()=>check(path,before,{...after,blockNumber:'10'}),/ordered/));
test('rejects chain mismatch',()=>assert.throws(()=>check(path,before,{...after,chainId:'1'}),/chain mismatch/));
test('rejects invalid block hash',()=>assert.throws(()=>check(path,before,{...after,blockHash:'abc'}),/blockHash/));
test('rejects negative balances',()=>assert.throws(()=>check(path,before,{...after,balances:[entry('native','-1'),entry(token,'37')]}),/canonical/));
test('rejects extra snapshot asset',()=>assert.throws(()=>check(path,before,{...after,balances:[...after.balances,entry('0x'+'3'.repeat(40),'9')]}),/coverage/));
test('rejects zero declared payments',()=>assert.throws(()=>check({...path,outcome:[{recipient,asset:'native',deltaWei:'0'}]},before,after),/Zero/));
